const { before, test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const Module = require("node:module");
const path = require("node:path");
const ts = require("typescript");

const FRONTEND_ROOT = path.resolve(__dirname, "..");
const BUILD_ROOT = path.join(FRONTEND_ROOT, process.env.NEXT_DIST_DIR || ".next");
const APP_BUILD_ROOT = path.join(BUILD_ROOT, "server", "app");
const SITE_ORIGIN = "https://www.fixwheel.app";

// Load the same TypeScript registries used by the application without adding
// a test-runner dependency solely for TypeScript execution.
const originalResolveFilename = Module._resolveFilename;
Module._resolveFilename = function resolveFilename(request, parent, isMain, options) {
  const resolvedRequest = request.startsWith("@/")
    ? path.join(FRONTEND_ROOT, request.slice(2))
    : request;
  return originalResolveFilename.call(this, resolvedRequest, parent, isMain, options);
};

require.extensions[".ts"] = function transpileTypeScript(module, filename) {
  const source = fs.readFileSync(filename, "utf8");
  const output = ts.transpileModule(source, {
    fileName: filename,
    compilerOptions: {
      esModuleInterop: true,
      jsx: ts.JsxEmit.ReactJSX,
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
    },
  });
  module._compile(output.outputText, filename);
};

const {
  PAGE_FAMILY_REGISTRY,
  PUBLIC_CITY_SLUGS,
  ROUTE_VALIDATION_BASELINE,
  SITEMAP_DOCUMENTS,
} = require("../lib/pageRegistry.ts");
const { BRAND_REGISTRY, getRetiredBrandRedirect } = require("../lib/brandRegistry.ts");

let sitemapEntries;
let routeResults;
let redirects;

function extractLocations(xml) {
  return Array.from(xml.matchAll(/<loc>(.*?)<\/loc>/g), (match) => match[1]);
}

function toPath(url) {
  const parsed = new URL(url, SITE_ORIGIN);
  return `${parsed.pathname}${parsed.search}`;
}

function normalizePath(value) {
  const pathname = toPath(value);
  return pathname !== "/" ? pathname.replace(/\/$/, "") : pathname;
}

function extractCanonicals(html) {
  return Array.from(
    html.matchAll(/<link\s+rel=["']canonical["']\s+href=["']([^"']+)["'][^>]*>/gi),
    (match) => match[1],
  );
}

function extractOpenGraphUrls(html) {
  return Array.from(html.matchAll(/<meta\s+property=["']og:url["']\s+content=["']([^"']+)["'][^>]*>/gi), (match) => match[1]);
}

function builtHtmlPath(routePath) {
  const cleanPath = normalizePath(routePath).replace(/^\//, "");
  return path.join(APP_BUILD_ROOT, cleanPath || "index") + ".html";
}

function findRedirect(routePath) {
  return redirects.find(({ regex }) => new RegExp(regex).test(routePath));
}

function inspectBuiltRoute(routePath) {
  const target = getRetiredBrandRedirect(normalizePath(routePath), PUBLIC_CITY_SLUGS);
  if (target) return { path: routePath, status: 308, canonicals: [], redirect: { destination: target, statusCode: 308 } };
  const htmlPath = builtHtmlPath(routePath);
  if (fs.existsSync(htmlPath)) {
    const html = fs.readFileSync(htmlPath, "utf8");
    return { path: routePath, status: 200, canonicals: extractCanonicals(html), redirect: null };
  }

  const redirect = findRedirect(routePath);
  if (redirect) {
    return { path: routePath, status: redirect.statusCode, canonicals: [], redirect };
  }

  return { path: routePath, status: 404, canonicals: [], redirect: null };
}

before(() => {
  assert.ok(
    fs.existsSync(path.join(BUILD_ROOT, "BUILD_ID")),
    "A production build is required. Run this suite with `npm run test:routes`.",
  );

  redirects = JSON.parse(
    fs.readFileSync(path.join(BUILD_ROOT, "routes-manifest.json"), "utf8"),
  ).redirects;

  sitemapEntries = new Map();
  for (const { name } of SITEMAP_DOCUMENTS) {
    const bodyPath = path.join(APP_BUILD_ROOT, `${name}.body`);
    assert.ok(fs.existsSync(bodyPath), `${name} must be generated by the production build`);
    const xml = fs.readFileSync(bodyPath, "utf8");
    sitemapEntries.set(name, extractLocations(xml).map(normalizePath));
  }

  const uniquePaths = Array.from(new Set(Array.from(sitemapEntries.values()).flat()));
  routeResults = uniquePaths.map(inspectBuiltRoute);
});

test("sitemap index contains exactly the registered sitemap documents", () => {
  const sitemapIndex = fs.readFileSync(path.join(APP_BUILD_ROOT, "sitemap.xml.body"), "utf8");
  const actual = extractLocations(sitemapIndex).map(normalizePath);
  const expected = SITEMAP_DOCUMENTS.map(({ path: sitemapPath }) => sitemapPath);
  assert.deepEqual(actual, expected);
});

test("every indexable page family has declared sitemap ownership", () => {
  const allowedMissing = new Set(ROUTE_VALIDATION_BASELINE.missingSitemapFamilyIds);
  const missing = PAGE_FAMILY_REGISTRY
    .filter((family) => family.indexable && family.sitemapDocuments.length === 0)
    .map((family) => family.id)
    .sort();
  assert.deepEqual(missing, [...allowedMissing].sort());
});

test("utility and transactional routes never enter a sitemap", () => {
  const sitemapPaths = new Set(Array.from(sitemapEntries.values()).flat());
  const exactNonIndexablePaths = PAGE_FAMILY_REGISTRY
    .filter((family) => !family.indexable)
    .map((family) => family.routePattern)
    .filter((routePattern) => !/[\[\]{*]/.test(routePattern));
  const infrastructurePaths = [
    "/robots.txt",
    "/sitemap.xml",
    "/api/revalidate-blog",
    ...SITEMAP_DOCUMENTS.map(({ path: sitemapPath }) => sitemapPath),
  ];
  const leaked = [...exactNonIndexablePaths, ...infrastructurePaths]
    .filter((routePath) => sitemapPaths.has(routePath));
  assert.deepEqual(leaked, []);
});

test("sitemap duplication matches the explicit temporary baseline", () => {
  const repeatedWithin = [];
  for (const [sitemapName, entries] of sitemapEntries) {
    const counts = new Map();
    for (const entry of entries) counts.set(entry, (counts.get(entry) || 0) + 1);
    for (const [entry, count] of counts) {
      if (count > 1) repeatedWithin.push(`${sitemapName}:${entry}`);
    }
  }
  const expectedRepeated = ROUTE_VALIDATION_BASELINE.repeatedWithinSitemap
    .map((routePath) => `service.xml:${routePath}`)
    .sort();
  assert.deepEqual(repeatedWithin.sort(), expectedRepeated);

  const sitemapOwners = new Map();
  for (const [sitemapName, entries] of sitemapEntries) {
    for (const entry of new Set(entries)) {
      const owners = sitemapOwners.get(entry) || [];
      owners.push(sitemapName);
      sitemapOwners.set(entry, owners);
    }
  }
  const duplicatedAcross = Array.from(sitemapOwners)
    .filter(([, owners]) => owners.length > 1)
    .map(([routePath]) => routePath)
    .sort();
  assert.deepEqual(
    duplicatedAcross,
    [...ROUTE_VALIDATION_BASELINE.duplicatedAcrossSitemaps].sort(),
  );
});

test("brand slugs and aliases have one registry owner", () => {
  const owners = new Map();
  for (const brand of BRAND_REGISTRY) {
    for (const slug of [brand.publicSlug, ...brand.legacyAliases]) {
      const existing = owners.get(slug);
      assert.equal(existing, undefined, `${slug} belongs to both ${existing} and ${brand.displayName}`);
      owners.set(slug, brand.displayName);
    }
  }
});

test("approved brand winners are indexable and retired aliases redirect without chains", () => {
  const brandSitemap = new Set(sitemapEntries.get("brand.xml"));
  for (const brand of BRAND_REGISTRY) {
    const winner = inspectBuiltRoute(`/${brand.publicSlug}`);
    assert.equal(winner.status, 200, `/${brand.publicSlug} must serve a page`);
    assert.deepEqual(winner.canonicals.map(normalizePath), [`/${brand.publicSlug}`]);
    const winnerHtml = fs.readFileSync(builtHtmlPath(`/${brand.publicSlug}`), "utf8");
    assert.deepEqual(extractOpenGraphUrls(winnerHtml).map(normalizePath), [`/${brand.publicSlug}`]);
    assert.equal(brandSitemap.has(`/${brand.publicSlug}`), brand.includeInSitemap && brand.indexable);
    for (const alias of brand.legacyAliases) {
      const result = inspectBuiltRoute(`/${alias}`);
      if (brand.preserveLegacyPages) {
        assert.equal(result.status, 200, `/${alias} must remain public during impression comparison`);
        assert.ok(brandSitemap.has(`/${alias}`), `/${alias} must remain in brand.xml while preserved`);
        const canonicals = result.canonicals.map(normalizePath);
        assert.deepEqual(canonicals, [`/${alias}`], `/${alias} must remain self-canonical while preserved`);

        for (const city of PUBLIC_CITY_SLUGS) {
          const cityAliasPath = `/${city}/${alias}`;
          const cityResult = inspectBuiltRoute(cityAliasPath);
          assert.equal(cityResult.status, 200, `${cityAliasPath} must remain public during comparison`);
          assert.ok(brandSitemap.has(cityAliasPath), `${cityAliasPath} must remain in brand.xml`);
          assert.deepEqual(
            cityResult.canonicals.map(normalizePath),
            [cityAliasPath],
            `${cityAliasPath} must remain self-canonical while preserved`,
          );
        }
      } else {
        assert.equal(result.status, 308, `/${alias} must permanently redirect`);
        assert.equal(result.redirect.destination, brand.redirectTarget);
        assert.ok(!brandSitemap.has(`/${alias}`), `/${alias} must leave brand.xml after retirement`);
        assert.equal(fs.existsSync(builtHtmlPath(`/${alias}`)), false, `/${alias} must not generate static HTML`);
        assert.equal(inspectBuiltRoute(brand.redirectTarget).status, 200, "redirect target must be live");
        for (const entries of sitemapEntries.values()) {
          assert.ok(!entries.includes(`/${alias}`), `/${alias} must not appear in any sitemap`);
        }
        for (const city of PUBLIC_CITY_SLUGS) {
          const oldCity = `/${city}/${alias}`;
          const cityTarget = `/${city}/${brand.publicSlug}`;
          assert.equal(inspectBuiltRoute(oldCity).status, 308);
          assert.equal(getRetiredBrandRedirect(oldCity, PUBLIC_CITY_SLUGS), cityTarget);
          assert.equal(inspectBuiltRoute(cityTarget).status, 200);
          assert.ok(!brandSitemap.has(oldCity));
          assert.ok(brandSitemap.has(cityTarget));
        }
        for (const model of brand.modelFamilySlugs) {
          const target = `/${brand.publicSlug}/${model}`;
          assert.equal(getRetiredBrandRedirect(`/${alias}/${model}`, PUBLIC_CITY_SLUGS), target);
          assert.equal(inspectBuiltRoute(target).status, 200);
        }
      }
    }
  }
});

test("brand sitemap count follows registry policy and no redirects chain", () => {
  const { BRAND_SITEMAP_SERVICE_PATHS } = require("../lib/pageRegistry.ts");
  const published = BRAND_REGISTRY.filter((entry) => entry.indexable && entry.includeInSitemap);
  const aliases = BRAND_REGISTRY.flatMap((entry) => entry.preserveLegacyPages ? entry.legacyAliases : []);
  const families = BRAND_REGISTRY.reduce((sum, entry) => sum + entry.modelFamilySlugs.length, 0);
  const expected = 1 + (published.length + aliases.length) * (1 + PUBLIC_CITY_SLUGS.length)
    + BRAND_SITEMAP_SERVICE_PATHS.length + families;
  assert.equal(sitemapEntries.get("brand.xml").length, expected);
  for (const entry of BRAND_REGISTRY) {
    if (!entry.preserveLegacyPages) {
      assert.equal(getRetiredBrandRedirect(entry.redirectTarget, PUBLIC_CITY_SLUGS), undefined);
    }
  }
});

test("rendered internal links never target retired brand URLs", () => {
  const retired = BRAND_REGISTRY.flatMap((entry) => entry.preserveLegacyPages ? [] : entry.legacyAliases);
  const pages = ["/", "/brands", "/electric-vehicle", "/services/basic-service",
    ...BRAND_REGISTRY.map((entry) => `/${entry.publicSlug}`),
    ...PUBLIC_CITY_SLUGS.flatMap((city) => BRAND_REGISTRY.map((entry) => `/${city}/${entry.publicSlug}`))];
  for (const routePath of pages) {
    const filename = builtHtmlPath(routePath);
    if (!fs.existsSync(filename)) continue;
    const html = fs.readFileSync(filename, "utf8");
    for (const alias of retired) {
      const escaped = alias.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const link = new RegExp(`href=["']/(?:${PUBLIC_CITY_SLUGS.join("|")}/)?${escaped}(?:[/?#"'])`, "i");
      assert.ok(!link.test(html), `${routePath} links to retired /${alias}`);
    }
  }
});

test("every sitemap URL resolves to a generated page or configured redirect", () => {
  const failures = routeResults.filter(({ status }) => status === 404 || status >= 500);
  assert.deepEqual(failures, []);
});

test("HTML sitemap pages do not publish conflicting canonical URLs", () => {
  const malformed = routeResults.filter(({ canonicals }) => canonicals.length > 1);
  assert.deepEqual(malformed, []);

  const canonicalOwners = new Map();
  for (const result of routeResults) {
    if (result.status !== 200 || result.canonicals.length !== 1) continue;
    const canonicalPath = normalizePath(result.canonicals[0]);
    const owners = canonicalOwners.get(canonicalPath) || [];
    owners.push(result.path);
    canonicalOwners.set(canonicalPath, owners);
  }
  const conflicts = Array.from(canonicalOwners, ([canonical, paths]) => ({ canonical, paths }))
    .filter(({ paths }) => new Set(paths).size > 1);
  assert.deepEqual(conflicts, []);
});
